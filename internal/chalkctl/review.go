// 139-2: `chalkctl review` makes a review instance of chalk for app review.
// It runs on the host of production.
//
// The review instance has its own chalkd (chalkd-review), Postgres
// (postgres-review), volumes, env file, and network (chalk-review).
// Caddy is the only container on both networks. The review containers
// cannot reach the database or chalkd of production. The review instance
// shares Caddy and coturn with production. It runs the image of production
// chalkd.
//
// The review env file has CHALK_REVIEW_MODE=1, and init writes the row of
// review_instance into the review database. With both, password login on
// the review instance gives a session without the TOTP step (139-1).
// The env template of production never contains CHALK_REVIEW_MODE. Only
// reviewEnv appends it.

// Paths and names of the review instance.
const (
	DefaultReviewConfPath = "/etc/chalk/review.conf"
	DefaultReviewEnvPath  = "/etc/chalk/review.env"

	reviewPGContainer = "postgres-review"
	reviewChalkdUnit  = "chalkd-review.container"
	reviewChalkdSvc   = "chalkd-review.service"
	reviewPGSvc       = "chalk-review-postgres.service"
	reviewNetwork     = "chalk-review"
	caddyUnit         = "chalk-caddy.container"
	caddySvc          = "chalk-caddy.service"
)

// reviewUnitTemplates lists the Quadlet files of the review instance. The
// file name is also the template name.
var reviewUnitTemplates = []string{
	"chalk-review.network",
	"chalk-review-pgdata.volume",
	"chalk-review-blobs.volume",
	"chalk-review-postgres.container",
	"chalkd-review.container",
}

// reviewVolumes are the podman volumes of the review instance.
var reviewVolumes = []string{"chalk-review-pgdata", "chalk-review-blobs"}

// ReviewConf is the persisted state of the review instance (review.conf).
// The zero value means that there is no review instance.
type ReviewConf struct {
	Domain string // the public hostname of the review instance
	Up     bool   // true if the review instance runs
}

// Exists reports whether the review instance exists.
func (c ReviewConf) Exists() bool { return c.Domain != "" }

// LoadReviewConf reads review.conf at path. A missing file is the zero
// ReviewConf and no error.
func LoadReviewConf(path string) (ReviewConf, error) {
	var c ReviewConf
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return c, nil
		}
		return c, fmt.Errorf("open %s: %w", path, err)
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	line := 0
	for sc.Scan() {
		line++
		raw := strings.TrimSpace(sc.Text())
		if raw == "" || strings.HasPrefix(raw, "#") {
			continue
		}
		k, v, ok := strings.Cut(raw, "=")
		if !ok {
			return c, fmt.Errorf("%s:%d: not KEY=value: %q", path, line, raw)
		}
		switch strings.TrimSpace(k) {
		case "DOMAIN":
			c.Domain = strings.TrimSpace(v)
		case "UP":
			b, err := strconv.ParseBool(strings.TrimSpace(v))
			if err != nil {
				return c, fmt.Errorf("%s:%d: UP not a bool: %q", path, line, v)
			}
			c.Up = b
		}
	}
	return c, sc.Err()
}

// Save writes c to path with mode 0644. The file has no secrets.
func (c ReviewConf) Save(path string) error {
	data := fmt.Sprintf("# chalk -- review instance (generated by chalkctl review).\nDOMAIN=%s\nUP=%t\n", c.Domain, c.Up)
	return writeFile(path, []byte(data), 0o644)
}

// ReviewParams holds the values of the review unit templates.
type ReviewParams struct {
	Image        string // ghcr.io/owner/chalk (no tag)
	Version      string // written in a comment in the unit
	Digest       string // the digest of production chalkd
	PostgresTag  string
	VoiceEnabled bool
	TurnDomain   string // the domain of production, where coturn listens
	Up           bool   // if false, the units have no [Install] section and do not start at boot
}

// ReviewOptions holds the settings of the `chalkctl review` commands.
type ReviewOptions struct {
	Cfg            Config // the config of production
	Podman         *Podman
	ConfigPath     string
	StatePath      string
	EnvPath        string // the env file of production
	ReviewConfPath string
	ReviewEnvPath  string
	QuadletDir     string
	CaddyfileAt    string
	NoStart        bool // write the files, but do not start or stop a service
	Out            io.Writer
	// Confirm asks the operator before `review remove`. It must return true
	// to continue. If it is nil, defaults sets the prompt on stdin.
	Confirm func(prompt string) bool
}

func (o *ReviewOptions) defaults() {
	if o.Podman == nil {
		o.Podman = NewPodman()
	}
	if o.ConfigPath == "" {
		o.ConfigPath = DefaultConfigPath
	}
	if o.StatePath == "" {
		o.StatePath = DefaultStatePath
	}
	if o.EnvPath == "" {
		o.EnvPath = DefaultEnvPath
	}
	if o.ReviewConfPath == "" {
		o.ReviewConfPath = DefaultReviewConfPath
	}
	if o.ReviewEnvPath == "" {
		o.ReviewEnvPath = DefaultReviewEnvPath
	}
	if o.QuadletDir == "" {
		o.QuadletDir = DefaultQuadletDir
	}
	if o.CaddyfileAt == "" {
		o.CaddyfileAt = DefaultCaddyfile
	}
	if o.Out == nil {
		o.Out = os.Stdout
	}
	if o.Confirm == nil {
		o.Confirm = promptConfirm
	}
}

func (o *ReviewOptions) logf(format string, a ...any) {
	fmt.Fprintf(o.Out, "  "+format+"\n", a...)
}

// ReviewInitOptions holds the values of `chalkctl review init`.
type ReviewInitOptions struct {
	Domain        string // the hostname of the review instance
	AdminUsername string // the admin account of the review instance
	AdminEmail    string
}

// reviewEnv returns the env file of the review instance. It renders the env
// template of production with p, and then appends the review block.
func reviewEnv(p InitParams) ([]byte, error) {
	data, err := renderTemplate("chalk.env", p)
	if err != nil {
		return nil, err
	}
	block := "\n\n# --- review instance (docs/phases/PHASE-139-REVIEW.md) ---\n" +
		"# Password login gives a session without the TOTP step. chalkd uses this\n" +
		"# only if the database has the row of review_instance, and it does not\n" +
		"# start without that row. Never copy this line into the env file of production.\n" +
		"CHALK_REVIEW_MODE=1\n"
	return append([]byte(strings.TrimRight(string(data), "\n")), block...), nil
}

// ReviewInit makes the review instance. It does these steps:
//
//  1. Generate the secrets. Copy CHALK_TURN_SECRET from production.
//  2. Write review.env, the review units, and review.conf.
//  3. Start postgres-review, create the database roles, migrate the
//     database, and write the row of review_instance.
//  4. Start chalkd-review, write the Caddy unit and the Caddyfile, and
//     restart Caddy, which then joins the review network.
//
// Registration is open after init, so that the operator can make the demo
// accounts. `chalkctl review registration closed` closes it.
func ReviewInit(o ReviewOptions, ro ReviewInitOptions) error {
	o.defaults()
	cfg := o.Cfg

	// -- preflight -----------------------------------------------------------
	domain := strings.TrimSpace(ro.Domain)
	if domain == "" || strings.ContainsAny(domain, " /:") {
		return fmt.Errorf("--domain %q looks wrong: give the hostname of the review instance", ro.Domain)
	}
	if strings.EqualFold(domain, cfg.Domain) {
		return fmt.Errorf("--domain must not be the domain of production (%s)", cfg.Domain)
	}
	if strings.TrimSpace(ro.AdminUsername) == "" || !strings.Contains(ro.AdminEmail, "@") {
		return fmt.Errorf("the review instance needs --admin-username and --admin-email")
	}
	st, ok, err := LoadState(o.StatePath)
	if err != nil {
		return err
	}
	if !ok || st.CurrentDigest == "" {
		return fmt.Errorf("production is not initialized (%s missing) -- run `chalkctl init` first", o.StatePath)
	}
	existing, err := LoadReviewConf(o.ReviewConfPath)
	if err != nil {
		return err
	}
	if existing.Exists() {
		return fmt.Errorf("the review instance %s exists (%s) -- run `chalkctl review remove` first", existing.Domain, o.ReviewConfPath)
	}
	prodEnv, err := readEnvSecrets(o.EnvPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", o.EnvPath, err)
	}
	turn := prodEnv["CHALK_TURN_SECRET"]
	if cfg.VoiceEnabled && turn == "" {
		return fmt.Errorf("voice is on, but %s has no CHALK_TURN_SECRET to share with the review instance", o.EnvPath)
	}
	fmt.Fprintf(o.Out, "chalkctl review init: %s on %s (%s)\n", domain, cfg.Image, shortDigest(st.CurrentDigest))

	// -- secrets + env -------------------------------------------------------
	var pg, appPw, guestPw, totp, decoy, adminBoot, serverKey, vapidPriv, vapidPub string
	for _, gen := range []struct {
		dst *string
		fn  func() (string, error)
	}{
		{&pg, func() (string, error) { return genSecret(24) }},
		{&appPw, func() (string, error) { return genSecret(24) }},
		{&guestPw, func() (string, error) { return genSecret(24) }},
		{&totp, genTOTPEncKey},
		{&decoy, genDecoyKey},
		{&adminBoot, func() (string, error) { return genSecret(24) }},
		{&serverKey, genServerIDKey},
	} {
		if *gen.dst, err = gen.fn(); err != nil {
			return err
		}
	}
	if vapidPriv, vapidPub, err = genVAPIDKey(); err != nil {
		return err
	}
	env, err := reviewEnv(InitParams{
		Domain:               domain,
		DBHost:               reviewPGContainer,
		VoiceEnabled:         cfg.VoiceEnabled,
		VoiceMaxParticipants: cfg.VoiceMaxParticipants,
		PGPassword:           pg,
		PGAppPassword:        appPw,
		PGGuestPassword:      guestPw,
		TurnSecret:           turn,
		TOTPEncKey:           totp,
		ServerIDKey:          serverKey,
		AuthDecoyKey:         decoy,
		AdminBootstrapToken:  adminBoot,
		AdminUsername:        ro.AdminUsername,
		AdminEmail:           ro.AdminEmail,
		OpenRegistration:     true,
		AttachMaxBytes:       cfg.AttachMaxBytes,
		LinkPreviewEnabled:   cfg.LinkPreviewEnabled,
		LinkPreviewDomains:   cfg.LinkPreviewDomains,
		// Guest links hand out access to strangers. The demo server has no
		// use for them.
		EphemeralEnabled: false,
		WrapSigRequired:  true,
		PushEnabled:      true,
		VAPIDPublicKey:   vapidPub,
		VAPIDPrivateKey:  vapidPriv,
		VAPIDSubject:     pushSubject(cfg.PushSubject, domain),
		OutboundIPv4Only: cfg.OutboundIPv4Only,
	})
	if err != nil {
		return err
	}
	if err := writeFile(o.ReviewEnvPath, env, 0o600); err != nil {
		return err
	}
	o.logf("wrote %s (0600)", o.ReviewEnvPath)

	// -- units + review.conf --------------------------------------------------
	rp := ReviewParams{
		Image:        cfg.Image,
		Version:      st.CurrentVersion,
		Digest:       st.CurrentDigest,
		PostgresTag:  cfg.PostgresTag,
		VoiceEnabled: cfg.VoiceEnabled,
		TurnDomain:   cfg.Domain,
		Up:           true,
	}
	if err := writeReviewUnits(o.QuadletDir, rp); err != nil {
		return err
	}
	o.logf("wrote %d review units to %s", len(reviewUnitTemplates), o.QuadletDir)
	rc := ReviewConf{Domain: domain, Up: true}
	if err := rc.Save(o.ReviewConfPath); err != nil {
		return err
	}

	if !o.NoStart {
		if _, err := Systemctl("daemon-reload"); err != nil {
			return err
		}
		o.logf("starting %s", reviewPGSvc)
		if _, err := Systemctl("start", reviewPGSvc); err != nil {
			return fmt.Errorf("start %s (check `journalctl -u %s`): %w", reviewPGSvc, reviewPGSvc, err)
		}
		o.logf("creating database roles (chalk_app, chalk_guest)")
		if err := ensureDBRolesIn(o.Podman, reviewPGContainer, appPw, guestPw); err != nil {
			return err
		}
		// chalkd checks the review_instance row at start (139-1). The
		// table exists only after the migrations. So a one-shot chalkd
		// migrates first. --migrate-only exits before the check.
		o.logf("migrating the review database")
		if _, err := o.Podman.run(reviewMigrateArgs(o.ReviewEnvPath, cfg.Image, st.CurrentDigest)...); err != nil {
			return fmt.Errorf("migrate the review database: %w", err)
		}
		o.logf("marking the review database (review_instance)")
		if err := markReviewDB(o.Podman); err != nil {
			return err
		}
		o.logf("starting %s", reviewChalkdSvc)
		if _, err := Systemctl("start", reviewChalkdSvc); err != nil {
			return fmt.Errorf("start %s (check `journalctl -u %s`): %w", reviewChalkdSvc, reviewChalkdSvc, err)
		}
	}

	// -- Caddy ----------------------------------------------------------------
	if err := o.writeCaddy(rc); err != nil {
		return err
	}
	if !o.NoStart {
		if _, err := Systemctl("daemon-reload"); err != nil {
			return err
		}
		// A restart is necessary: a reload does not add Caddy to a new
		// network. The restart drops the connections of production for a
		// moment.
		o.logf("restarting %s, so that Caddy joins the %s network", caddySvc, reviewNetwork)
		if _, err := Systemctl("restart", caddySvc); err != nil {
			return fmt.Errorf("restart %s (check `journalctl -u %s`): %w", caddySvc, caddySvc, err)
		}
	}

	fmt.Fprintf(o.Out, "\ndone. https://%s serves after Caddy issues its certificate, if the DNS record points to this host.\n", domain)
	fmt.Fprintf(o.Out, "admin: create the %q account at:\n", ro.AdminUsername)
	fmt.Fprintf(o.Out, "       https://%s/?admin_token=%s\n", domain, adminBoot)
	fmt.Fprintf(o.Out, "Registration is open. Make the demo accounts now.\n")
	fmt.Fprintf(o.Out, "Then run: chalkctl review registration closed\n")
	return nil
}

// reviewMigrateArgs returns the podman arguments of the one-shot migration.
func reviewMigrateArgs(envPath, image, digest string) []string {
	return []string{
		"run", "--rm",
		"--network", reviewNetwork,
		"--env-file", envPath,
		"-e", "CHALK_TLS_MODE=off",
		image + "@" + digest,
		"--migrate-only",
	}
}

// markReviewSQL writes the row of review_instance. A second run changes
// nothing.
const markReviewSQL = "INSERT INTO review_instance DEFAULT VALUES ON CONFLICT DO NOTHING;\n"

// markReviewDB writes the row of review_instance into the review database.
// It never touches the database of production, because the container is
// postgres-review.
func markReviewDB(p *Podman) error {
	if err := p.ExecIn(strings.NewReader(markReviewSQL), reviewPGContainer,
		"psql", "-U", "chalk", "-d", "chalk", "-q", "-v", "ON_ERROR_STOP=1"); err != nil {
		return fmt.Errorf("mark the review database: %w", err)
	}
	return nil
}

// writeReviewUnits renders the review units into dir.
func writeReviewUnits(dir string, rp ReviewParams) error {
	for _, name := range reviewUnitTemplates {
		data, err := renderTemplateData(name, rp)
		if err != nil {
			return err
		}
		if err := writeFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// writeCaddy writes the Caddy unit and the Caddyfile for the review state rc.
// The maintenance mode of production stays as the state file records it.
func (o *ReviewOptions) writeCaddy(rc ReviewConf) error {
	st, _, err := LoadState(o.StatePath)
	if err != nil {
		return err
	}
	unit, err := renderTemplate(caddyUnit, InitParams{CaddyTag: o.Cfg.CaddyTag, ReviewDomain: rc.Domain})
	if err != nil {
		return err
	}
	if err := writeFile(filepath.Join(o.QuadletDir, caddyUnit), unit, unitMode(caddyUnit)); err != nil {
		return err
	}
	if err := writeCaddyfile(o.Cfg, o.CaddyfileAt, st.Maintenance, st.MaintenanceMessage, rc); err != nil {
		return err
	}
	o.logf("wrote %s and %s", filepath.Join(o.QuadletDir, caddyUnit), o.CaddyfileAt)
	return nil
}

// reviewParamsFromUnit returns the ReviewParams for a re-render of the units.
// The image and the digest come from the chalkd-review unit on disk, so a
// re-render keeps the pin.
func (o *ReviewOptions) reviewParamsFromUnit(up bool) (ReviewParams, error) {
	path := filepath.Join(o.QuadletDir, reviewChalkdUnit)
	b, err := os.ReadFile(path)
	if err != nil {
		return ReviewParams{}, fmt.Errorf("read %s: %w", path, err)
	}
	ref := ""
	version := ""
	for _, ln := range splitLines(string(b)) {
		if hasPrefix(ln, "Image=") {
			ref = strings.TrimPrefix(ln, "Image=")
		}
		if v, ok := strings.CutPrefix(ln, "#   image  : "); ok {
			if i := strings.LastIndex(v, ":"); i >= 0 {
				version = v[i+1:]
			}
		}
	}
	image, digest, ok := strings.Cut(ref, "@")
	if !ok {
		return ReviewParams{}, fmt.Errorf("no Image=<image>@<digest> line in %s", path)
	}
	return ReviewParams{
		Image:        image,
		Version:      version,
		Digest:       digest,
		PostgresTag:  o.Cfg.PostgresTag,
		VoiceEnabled: o.Cfg.VoiceEnabled,
		TurnDomain:   o.Cfg.Domain,
		Up:           up,
	}, nil
}

// ReviewSetUp starts the review instance if up is true, and stops it if up
// is false. It renders the units again, so that the state stays the same
// after a reboot. It also renders the Caddyfile again: the proxy when up,
// the "off" page when down. It does not stop or restart production. Caddy
// reloads in place.
func ReviewSetUp(o ReviewOptions, up bool) error {
	o.defaults()
	rc, err := LoadReviewConf(o.ReviewConfPath)
	if err != nil {
		return err
	}
	if !rc.Exists() {
		return fmt.Errorf("there is no review instance (%s missing) -- run `chalkctl review init` first", o.ReviewConfPath)
	}
	rp, err := o.reviewParamsFromUnit(up)
	if err != nil {
		return err
	}
	if err := writeReviewUnits(o.QuadletDir, rp); err != nil {
		return err
	}
	rc.Up = up
	if !o.NoStart {
		if _, err := Systemctl("daemon-reload"); err != nil {
			return err
		}
		if up {
			for _, svc := range []string{reviewPGSvc, reviewChalkdSvc} {
				o.logf("starting %s", svc)
				if _, err := Systemctl("start", svc); err != nil {
					return fmt.Errorf("start %s (check `journalctl -u %s`): %w", svc, svc, err)
				}
			}
		} else {
			for _, svc := range []string{reviewChalkdSvc, reviewPGSvc} {
				o.logf("stopping %s", svc)
				if _, err := Systemctl("stop", svc); err != nil {
					return fmt.Errorf("stop %s: %w", svc, err)
				}
			}
		}
	}
	if err := rc.Save(o.ReviewConfPath); err != nil {
		return err
	}
	st, _, err := LoadState(o.StatePath)
	if err != nil {
		return err
	}
	if err := writeCaddyfile(o.Cfg, o.CaddyfileAt, st.Maintenance, st.MaintenanceMessage, rc); err != nil {
		return err
	}
	if !o.NoStart {
		if err := reloadCaddy(o.Podman, o.Out); err != nil {
			return err
		}
	}
	fmt.Fprintf(o.Out, "the review instance %s is %s.\n", rc.Domain, upDown(up))
	return nil
}

// ReviewRegistration opens or closes registration on the review instance,
// and restarts chalkd-review if it runs.
func ReviewRegistration(o ReviewOptions, open bool) error {
	o.defaults()
	rc, err := LoadReviewConf(o.ReviewConfPath)
	if err != nil {
		return err
	}
	if !rc.Exists() {
		return fmt.Errorf("there is no review instance (%s missing)", o.ReviewConfPath)
	}
	if _, err := setEnvValue(o.ReviewEnvPath, "CHALK_OPEN_REGISTRATION", strconv.FormatBool(open)); err != nil {
		return err
	}
	o.logf("set CHALK_OPEN_REGISTRATION=%t in %s", open, o.ReviewEnvPath)
	if rc.Up && !o.NoStart {
		if _, err := Systemctl("restart", reviewChalkdSvc); err != nil {
			return fmt.Errorf("restart %s: %w", reviewChalkdSvc, err)
		}
		o.logf("restarted %s", reviewChalkdSvc)
	}
	return nil
}

// ReviewStatus prints the state of the review instance.
func ReviewStatus(o ReviewOptions) error {
	o.defaults()
	rc, err := LoadReviewConf(o.ReviewConfPath)
	if err != nil {
		return err
	}
	if !rc.Exists() {
		fmt.Fprintln(o.Out, "review instance: none")
		return nil
	}
	env, err := readEnvSecrets(o.ReviewEnvPath)
	if err != nil {
		return fmt.Errorf("read %s: %w", o.ReviewEnvPath, err)
	}
	fmt.Fprintf(o.Out, "review instance: %s\n", rc.Domain)
	fmt.Fprintf(o.Out, "state:           %s\n", upDown(rc.Up))
	fmt.Fprintf(o.Out, "registration:    %s\n", openClosed(env["CHALK_OPEN_REGISTRATION"]))
	fmt.Fprintf(o.Out, "review mode:     %s\n", onOff(env["CHALK_REVIEW_MODE"] != ""))
	if !o.NoStart {
		for _, svc := range []string{reviewChalkdSvc, reviewPGSvc} {
			s, _ := Systemctl("is-active", svc)
			fmt.Fprintf(o.Out, "%-30s %s\n", svc+":", strings.TrimSpace(s))
		}
	}
	return nil
}

// ReviewRemove deletes the review instance: its services, units, volumes,
// network, env file, and review.conf. First it asks the operator to type the
// domain of the review instance. Then it writes the Caddy unit and the
// Caddyfile without the review lines, and restarts Caddy.
func ReviewRemove(o ReviewOptions) error {
	o.defaults()
	rc, err := LoadReviewConf(o.ReviewConfPath)
	if err != nil {
		return err
	}
	if !rc.Exists() {
		return fmt.Errorf("there is no review instance (%s missing)", o.ReviewConfPath)
	}
	if !o.Confirm(fmt.Sprintf(
		"CAUTION: This deletes the review instance %s and its database. You cannot undo it.\nType the domain (%s) to confirm: ",
		rc.Domain, rc.Domain)) {
		return fmt.Errorf("aborted: removal not confirmed")
	}
	if !o.NoStart {
		for _, svc := range []string{reviewChalkdSvc, reviewPGSvc} {
			_, _ = Systemctl("stop", svc)
		}
	}
	for _, name := range reviewUnitTemplates {
		if err := os.Remove(filepath.Join(o.QuadletDir, name)); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	if err := o.writeCaddy(ReviewConf{}); err != nil {
		return err
	}
	if !o.NoStart {
		if _, err := Systemctl("daemon-reload"); err != nil {
			return err
		}
		o.logf("restarting %s, so that Caddy leaves the %s network", caddySvc, reviewNetwork)
		if _, err := Systemctl("restart", caddySvc); err != nil {
			return fmt.Errorf("restart %s: %w", caddySvc, err)
		}
		for _, v := range reviewVolumes {
			if _, err := o.Podman.run("volume", "rm", "--force", v); err != nil {
				fmt.Fprintf(o.Out, "  WARNING: could not remove volume %s: %v\n", v, err)
			}
		}
		if _, err := o.Podman.run("network", "rm", "--force", reviewNetwork); err != nil {
			fmt.Fprintf(o.Out, "  WARNING: could not remove network %s: %v\n", reviewNetwork, err)
		}
	}
	for _, path := range []string{o.ReviewEnvPath, o.ReviewConfPath} {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	fmt.Fprintf(o.Out, "the review instance %s is removed.\n", rc.Domain)
	return nil
}

// repinReview repins chalkd-review to image@digest after an update of
// production. It restarts chalkd-review if the instance is up. If there is no
// review instance, it does nothing.
func repinReview(quadletDir, confPath, image, digest string, logf func(string, ...any)) error {
	rc, err := LoadReviewConf(confPath)
	if err != nil || !rc.Exists() {
		return err
	}
	if err := repinUnitImage(filepath.Join(quadletDir, reviewChalkdUnit), image, digest); err != nil {
		return err
	}
	if !rc.Up {
		logf("repinned the review instance (it is down)")
		return nil
	}
	if _, err := Systemctl("daemon-reload"); err != nil {
		return err
	}
	if _, err := Systemctl("restart", reviewChalkdSvc); err != nil {
		return fmt.Errorf("restart %s: %w", reviewChalkdSvc, err)
	}
	logf("repinned and restarted the review instance")
	return nil
}

func upDown(up bool) string {
	if up {
		return "up"
	}
	return "down"
}

func openClosed(v string) string {
	if b, err := strconv.ParseBool(v); err == nil && b {
		return "open"
	}
	return "closed"
}
